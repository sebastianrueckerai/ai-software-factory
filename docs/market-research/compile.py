#!/usr/bin/env python3
"""Compile the front matter of every projects/*/report.md into one table and one steal list.

Usage: python3 compile.py            writes matrix.md next to this file and prints a summary
       python3 compile.py --check    only reports missing or malformed front matter
"""
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).parent
PROJECTS = HERE / "projects"
AXES = [
    "signals_intake", "control_plane", "sandbox_isolation", "verification",
    "policy_outside_model", "identity_per_task", "cost_control", "ux", "reseedable_selfhost",
]


def front_matter(path: Path):
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---"):
        raise ValueError("no front matter")
    end = text.find("\n---", 3)
    if end < 0:
        raise ValueError("unterminated front matter")
    data = yaml.safe_load(text[3:end])
    for key in ("name", "slug", "category", "similarity", "axes", "steal", "differs"):
        if key not in data:
            raise ValueError(f"missing key {key}")
    return data


def yn(value):
    if value is True:
        return "yes"
    if value is False:
        return "no"
    return value if value is not None else "?"


def main():
    check = "--check" in sys.argv
    rows, bad = [], []
    for report in sorted(PROJECTS.glob("*/report.md")):
        try:
            rows.append(front_matter(report))
        except Exception as exc:  # noqa: BLE001
            bad.append((report.parent.name, str(exc)))
    missing = sorted(p.name for p in PROJECTS.iterdir() if p.is_dir() and not (p / "report.md").exists())
    print(f"{len(rows)} reports parsed, {len(bad)} malformed, {len(missing)} folders without report")
    for slug, err in bad:
        print(f"  malformed: {slug}: {err}")
    for slug in missing:
        print(f"  missing:   {slug}")
    if check:
        return
    rows.sort(key=lambda r: (-int(r["similarity"]), r["category"], r["slug"]))
    out = ["# Matrix: every report's front matter in one table", "",
           "Generated by `compile.py`. Scores are relative to our design: 3 equals us, 5 clearly better, 0 absent.", "",
           "## Similarity and axes", "",
           "| Slug | Category | OSS | Self-host | Sim | " + " | ".join(a.replace("_", " ") for a in AXES) + " |",
           "|---|---|---|---|---|" + "---|" * len(AXES)]
    for r in rows:
        axes = r.get("axes") or {}
        out.append(f"| [{r['slug']}](projects/{r['slug']}/report.md) | {r['category']} | {yn(r.get('open_source'))} | "
                   f"{yn(r.get('self_hostable'))} | {r['similarity']} | "
                   + " | ".join(str(axes.get(a, "?")) for a in AXES) + " |")
    out += ["", "## Category averages", "", "| Category | Reports | Mean similarity | " + " | ".join(a.replace("_", " ") for a in AXES) + " |",
            "|---|---|---|" + "---|" * len(AXES)]
    cats = {}
    for r in rows:
        cats.setdefault(r["category"], []).append(r)
    for cat, rs in sorted(cats.items(), key=lambda kv: -len(kv[1])):
        def mean(key, sub=None):
            vals = [(x.get("axes") or {}).get(key) if sub else x.get(key) for x in rs]
            vals = [float(v) for v in vals if isinstance(v, (int, float))]
            return f"{sum(vals) / len(vals):.1f}" if vals else "?"
        out.append(f"| {cat} | {len(rs)} | {mean('similarity')} | " + " | ".join(mean(a, True) for a in AXES) + " |")
    out += ["", "## Steal items, by project", ""]
    for r in rows:
        out.append(f"### {r['name']} ({r['similarity']})")
        for item in r.get("steal") or []:
            out.append(f"- {item}")
        out.append("")
    out += ["## Differs items, by project", ""]
    for r in rows:
        out.append(f"### {r['name']}")
        for item in r.get("differs") or []:
            out.append(f"- {item}")
        out.append("")
    out += ["## Verdict lines", "", "| Slug | UX verdict | Slop verdict |", "|---|---|---|"]
    for r in rows:
        out.append(f"| {r['slug']} | {r.get('ux_verdict', '')} | {r.get('slop_verdict', '')} |")
    (HERE / "matrix.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote matrix.md")


if __name__ == "__main__":
    main()
